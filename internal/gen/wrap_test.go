// writeSrcDir 把一段接口源码放进临时包目录（附带可用的 DTO 与 import）。
func writeSrcDir(t *testing.T, src string) string {
	t.Helper()
	dir := t.TempDir()
	content := "package p\n\nimport \"context\"\n\nvar _ = context.Background\n\ntype Req struct{}\ntype Rep struct{}\n\n" + src + "\n"
	if err := os.WriteFile(filepath.Join(dir, "s.go"), []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	return dir
}

func TestWrapInvalidSignatures(t *testing.T) {
	cases := []struct {
		name    string
		src     string
		iface   string
		wantErr string
	}{
		{"无参数", "type S interface{ M() error }", "S", "没有参数"},
		{"缺 ctx 首参", "type S interface{ M(id string) error }", "S", "首参必须是 context.Context"},
		{"ctx 不是首参", "type S interface{ M(req Req, ctx context.Context) error }", "S", "首参必须是 context.Context"},
		{"参数过多", "type S interface{ M(ctx context.Context, a Req, b Req) error }", "S", "参数过多"},
		{"变参", "type S interface{ M(ctx context.Context, xs ...string) error }", "S", "禁止变参"},
		{"无返回值", "type S interface{ M(ctx context.Context) }", "S", "没有返回值"},
		{"返回值过多", "type S interface{ M(ctx context.Context) (Rep, Rep, error) }", "S", "返回值过多"},
		{"最后返回值非 error", "type S interface{ M(ctx context.Context) Rep }", "S", "最后一个返回值必须是 error"},
		{"error 不在末位", "type S interface{ M(ctx context.Context) (error, Rep) }", "S", "最后一个返回值必须是 error"},
		{"嵌入接口", "type T interface{ M(ctx context.Context) error }\ntype S interface{ T }", "S", "嵌入接口"},
		{"空接口", "type S interface{}", "S", "没有方法"},
		{"接口不存在", "type X struct{}", "S", "未找到接口"},
		{"不是接口类型", "type S struct{}", "S", "不是接口类型"},
		{"泛型接口", "type S[T any] interface{ M(ctx context.Context) error }", "S", "泛型"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			dir := writeSrcDir(t, tc.src)
			err := Wrap(dir, tc.iface, "sys", filepath.Join(dir, "out.gen.go"))
			wantErrContains(t, err, tc.wantErr)
			// 签名类错误必须能引导读者理解框架约束本身。
			if strings.Contains(err.Error(), "的方法") && !strings.Contains(err.Error(), "粗粒度") {
				t.Errorf("签名错误应说明契约形态约束，得到: %v", err)
			}
		})
	}
}

func TestWrapArgErrors(t *testing.T) {
	cases := []struct {
		name                    string
		src, iface, system, out string
		wantErr                 string
	}{
		{"缺参数", "", "", "", "", "-src"},
		{"system 非法", "x", "S", "My-Sys", "o.go", "-system"},
		{"src 不存在", filepath.Join(os.TempDir(), "appkit-gen-not-exist"), "S", "sys", "o.go", "读取 -src"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			wantErrContains(t, Wrap(tc.src, tc.iface, tc.system, tc.out), tc.wantErr)
		})
	}
}

// TestWrapImportsFromSignature 签名引用了别的包（含别名）时，import 被带进生成物。
func TestWrapImportsFromSignature(t *testing.T) {
	dir := t.TempDir()
	src := `package p

import (
	"context"
	"net/url"
	nu "net/url"
)

type S interface {
	Resolve(ctx context.Context, req url.Values) (nu.Values, error)
}
`
	if err := os.WriteFile(filepath.Join(dir, "s.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	out := filepath.Join(dir, "out.gen.go")
	if err := Wrap(dir, "S", "sys", out); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{`"net/url"`, `nu "net/url"`, `"github.com/forgeplex/appkit/contract"`, "req url.Values", "(nu.Values, error)"} {
		if !strings.Contains(string(got), want) {
			t.Errorf("生成物缺少 %q\n%s", want, got)
		}
	}
}

// TestWrapUnresolvableQualifier 签名引用的限定符没有对应 import 时报错并指出文件。
func TestWrapUnresolvableQualifier(t *testing.T) {
	dir := t.TempDir()
	src := "package p\n\nimport \"context\"\n\ntype S interface{ M(ctx context.Context, req ghost.Req) error }\n"
	if err := os.WriteFile(filepath.Join(dir, "s.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	err := Wrap(dir, "S", "sys", filepath.Join(dir, "out.gen.go"))
	wantErrContains(t, err, `"ghost"`)
	wantErrContains(t, err, "s.go")
}

// TestWrapGeneratedHeaderAndGofmt 生成物带标准头且已是 gofmt 形态。
func TestWrapGeneratedHeaderAndGofmt(t *testing.T) {
	out := filepath.Join(t.TempDir(), "out.gen.go")
	if err := Wrap("genfixture", "Service", "greet", out); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(got), "// Code generated by appkit gen. DO NOT EDIT.\n") {
		t.Error("缺少标准生成头")
	}
	if _, err := exec.LookPath("gofmt"); err == nil {
		cmd := exec.Command("gofmt", "-l", out)
		outp, err := cmd.Output()
		if err != nil {
			t.Fatalf("gofmt: %v", err)
		}
		if len(outp) != 0 {
			t.Errorf("生成物未通过 gofmt: %s", outp)
		}
	}
}

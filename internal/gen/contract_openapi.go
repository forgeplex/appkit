package gen

import (
	"bytes"
	"fmt"
	"strconv"
	"strings"
)

// renderOpenAPI 渲染 openapi.yaml——contract.yaml 的派生导出，供文档
// 与 oasdiff 门禁消费。事实源仍是 contract.yaml；本文件永不手写。
//
// 标量一律经 strconv.Quote 输出（yaml 双引号字符串兼容 Go 转义），
// doc 文本里的冒号/引号/换行不会破坏 yaml 结构。
func renderOpenAPI(doc *contractDoc) []byte {
	named := map[string]bool{}
	for _, t := range doc.Types {
		named[t.Name] = true
	}

	var b bytes.Buffer
	b.WriteString("# Code generated by appkit gen. DO NOT EDIT.\n")
	b.WriteString("# 事实源是 contract.yaml；本文件是派生导出，供文档与 oasdiff 门禁消费。\n")
	b.WriteString("openapi: 3.1.0\ninfo:\n")
	fmt.Fprintf(&b, "  title: %s\n", strconv.Quote(doc.System+" 契约"))
	fmt.Fprintf(&b, "  version: %s\n", strconv.Quote(strconv.Itoa(doc.Version)))

	b.WriteString("paths:\n")
	for _, m := range doc.Methods {
		fmt.Fprintf(&b, "  %s:\n    post:\n", strconv.Quote(m.Path))
		fmt.Fprintf(&b, "      operationId: %s\n", strconv.Quote(m.Name))
		fmt.Fprintf(&b, "      description: %s\n", strconv.Quote(m.Doc))
		if m.Idempotent {
			b.WriteString("      x-idempotent: true\n")
		}
		if len(m.Request) > 0 {
			b.WriteString("      requestBody:\n        required: true\n        content:\n")
			b.WriteString("          application/json:\n            schema:\n")
			fmt.Fprintf(&b, "              $ref: %s\n", strconv.Quote("#/components/schemas/"+m.Name+"Request"))
		}
		b.WriteString("      responses:\n        \"200\":\n          description: 成功\n")
		if len(m.Response) > 0 {
			b.WriteString("          content:\n            application/json:\n              schema:\n")
			fmt.Fprintf(&b, "                $ref: %s\n", strconv.Quote("#/components/schemas/"+m.Name+"Reply"))
		}
		// 错误响应形态唯一：problem+json，错误身份 = code 扩展成员。
		b.WriteString(`        default:
          description: 错误（错误身份 = code 扩展成员，跨网络重建后 apperr.Is 判定不变）
          content:
            application/problem+json:
              schema:
                $ref: '#/components/schemas/Problem'
`)
	}

	b.WriteString("components:\n  schemas:\n")
	for _, t := range doc.Types {
		renderOpenAPISchema(&b, t.Name, t.Doc, t.Fields, nil)
	}
	for _, m := range doc.Methods {
		if len(m.Request) > 0 {
			renderOpenAPISchema(&b, m.Name+"Request", m.Name+" 的请求 DTO。", m.Request, named)
		}
		if len(m.Response) > 0 {
			renderOpenAPISchema(&b, m.Name+"Reply", m.Name+" 的响应 DTO。", m.Response, named)
		}
	}
	// Problem 与 apperr.Problem 的 json 字段一一对应。
	b.WriteString(`    Problem:
      type: object
      description: RFC 9457 problem+json（apperr.Problem）。
      properties:
        type:
          type: string
        title:
          type: string
        status:
          type: integer
        detail:
          type: string
        code:
          type: string
          description: 错误身份；客户端据此重建 *apperr.Error。
        details:
          type: object
      required:
        - title
        - status
        - code
`)
	return b.Bytes()
}

// renderOpenAPISchema 渲染 components.schemas 下的一个 object schema。
func renderOpenAPISchema(b *bytes.Buffer, name, doc string, fields []fieldDef, named map[string]bool) {
	fmt.Fprintf(b, "    %s:\n      type: object\n", name)
	if doc != "" {
		fmt.Fprintf(b, "      description: %s\n", strconv.Quote(doc))
	}
	b.WriteString("      properties:\n")
	var required []string
	for _, f := range fields {
		fmt.Fprintf(b, "        %s:\n", strconv.Quote(f.Name))
		writeOpenAPIType(b, "          ", f.Type, named)
		if f.Required {
			required = append(required, f.Name)
		}
	}
	if len(required) > 0 {
		b.WriteString("      required:\n")
		for _, r := range required {
			fmt.Fprintf(b, "        - %s\n", strconv.Quote(r))
		}
	}
}

// writeOpenAPIType 按缩进写出字段类型（标量/数组/命名 DTO 引用）。
func writeOpenAPIType(b *bytes.Buffer, indent, typeStr string, named map[string]bool) {
	if strings.HasPrefix(typeStr, "[]") {
		fmt.Fprintf(b, "%stype: array\n%sitems:\n", indent, indent)
		writeOpenAPIType(b, indent+"  ", typeStr[2:], named)
		return
	}
	if named != nil && named[typeStr] {
		fmt.Fprintf(b, "%s$ref: %s\n", indent, strconv.Quote("#/components/schemas/"+typeStr))
		return
	}
	switch typeStr {
	case "string":
		fmt.Fprintf(b, "%stype: string\n", indent)
	case "int64":
		fmt.Fprintf(b, "%stype: integer\n%sformat: int64\n", indent, indent)
	case "bool":
		fmt.Fprintf(b, "%stype: boolean\n", indent)
	case "decimal":
		fmt.Fprintf(b, "%stype: string\n%sdescription: 十进制数字符串（用 money.Parse 解析，全系统禁 float 金额）\n", indent, indent)
	case "timestamp":
		fmt.Fprintf(b, "%stype: string\n%sformat: date-time\n", indent, indent)
	}
}
